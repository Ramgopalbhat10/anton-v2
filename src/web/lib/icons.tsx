/* Keyline duotone (MIT), exported under the names the app used with Lucide. Every icon carries `icon icon-<name>` for tests and styles. */

export type IconProps = Omit<SVGProps<SVGSVGElement>, 'ref' | 'children'> & { size?: number | string; strokeWidth?: number; absoluteStrokeWidth?: boolean };
export type IconComponent = ForwardRefExoticComponent<IconProps & RefAttributes<SVGSVGElement>>;

type KeylineProps = Omit<SVGProps<SVGSVGElement>, 'children'> & { size?: number | string };
type KeylineComponent = ComponentType<KeylineProps & { ref?: Ref<SVGSVGElement> }>;

function icon(name: string, Glyph: ComponentType<KeylineProps>): IconComponent {
	const KeylineGlyph = Glyph as KeylineComponent;
	const Drawn = forwardRef<SVGSVGElement, IconProps>(function Drawn({ className, absoluteStrokeWidth: _absoluteStrokeWidth, ...props }, ref) {
		return <KeylineGlyph ref={ref} className={cn('icon', `icon-${name}`, className)} {...props} />;
	});
	Drawn.displayName = name;
	return Drawn;
}

